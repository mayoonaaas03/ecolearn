create extension if not exists pgcrypto with schema extensions;

-- ---------- 1. Tabel data EconView ----------
create table if not exists public.materi (
  id text primary key, seq bigint generated by default as identity,
  bab text not null default '', t text not null default '', d text not null default '',
  poin text not null default '', rumus text not null default '', contoh text not null default '',
  sim smallint not null default 0
);
create table if not exists public.soal (
  id text primary key, seq bigint generated by default as identity,
  bab text not null default '', jenis text not null default 'pg', q text not null default '',
  opts text not null default '', "key" text not null default '',
  qd text not null default '', qs text not null default '', ai smallint not null default 0
);
create table if not exists public.modul (
  id text primary key, seq bigint generated by default as identity,
  t text not null default '', d text not null default '', name text not null default '', file_path text not null default ''
);
create table if not exists public.ppt (
  id text primary key, seq bigint generated by default as identity,
  t text not null default '', d text not null default '', name text not null default '', file_path text not null default ''
);
create table if not exists public.links (
  id text primary key, seq bigint generated by default as identity,
  n text not null default '', u text not null default ''
);

-- ---------- 2. Tabel keamanan (tidak bisa diakses dari frontend) ----------
create table if not exists public.access_config (
  id int primary key default 1 check (id = 1),
  code_hash text
);
create table if not exists public.access_grants (
  session_id uuid primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  expires_at timestamptz not null
);
create table if not exists public.access_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  attempted_at timestamptz not null default now()
);
alter table public.access_config enable row level security;
alter table public.access_grants enable row level security;
alter table public.access_attempts enable row level security;
revoke all on public.access_config, public.access_grants, public.access_attempts from anon, authenticated;

-- ---------- 3. Fungsi pemeriksa kode akses (berjalan di server) ----------
-- Apakah sesi login ini sudah lolos kode akses dan belum kedaluwarsa (12 jam)?
create or replace function public.is_verified()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.access_grants g
    where g.session_id = nullif(auth.jwt() ->> 'session_id', '')::uuid
      and g.user_id = auth.uid()
      and g.expires_at > now()
  );
$$;

-- Memeriksa kode 6 digit terhadap hash. Maksimal 5 salah per 15 menit.
create or replace function public.verify_access_code(kode text)
returns boolean
language plpgsql security definer
set search_path = public, extensions
as $$
declare
  uid uuid := auth.uid();
  sid uuid := nullif(auth.jwt() ->> 'session_id', '')::uuid;
  fails int;
  h text;
begin
  if uid is null or sid is null then return false; end if;
  delete from public.access_grants where expires_at < now();
  delete from public.access_attempts where attempted_at < now() - interval '1 day';
  select count(*) into fails from public.access_attempts
    where user_id = uid and attempted_at > now() - interval '15 minutes';
  if fails >= 5 then
    raise exception 'Terlalu banyak percobaan. Coba lagi dalam 15 menit.';
  end if;
  select code_hash into h from public.access_config where id = 1;
  if h is not null and kode ~ '^[0-9]{6}$' and h = crypt(kode, h) then
    delete from public.access_attempts where user_id = uid;
    insert into public.access_grants (session_id, user_id, expires_at)
      values (sid, uid, now() + interval '12 hours')
      on conflict (session_id) do update set expires_at = excluded.expires_at;
    return true;
  end if;
  insert into public.access_attempts (user_id) values (uid);
  return false;
end;
$$;

revoke all on function public.is_verified() from public, anon;
revoke all on function public.verify_access_code(text) from public, anon;
grant execute on function public.is_verified() to authenticated;
grant execute on function public.verify_access_code(text) to authenticated;

-- ---------- 4. Row Level Security: hanya sesi yang lolos kode akses ----------
do $$
declare t text;
begin
  foreach t in array array['materi','soal','modul','ppt','links'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists econview_akses on public.%I', t);
    execute format('create policy econview_akses on public.%I for all to authenticated using ((select public.is_verified())) with check ((select public.is_verified()))', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;

-- ---------- 5. Storage: bucket privat untuk PDF, DOCX, PPT, PPTX ----------
insert into storage.buckets (id, name, public, file_size_limit)
values ('econview-files', 'econview-files', false, 10485760)
on conflict (id) do update set public = false, file_size_limit = 10485760;

drop policy if exists econview_files_akses on storage.objects;
create policy econview_files_akses on storage.objects for all to authenticated
  using (bucket_id = 'econview-files' and (select public.is_verified()))
  with check (bucket_id = 'econview-files' and (select public.is_verified()));

-- ---------- 6. Sinkronisasi langsung antarperangkat (Realtime) ----------
do $$
declare t text;
begin
  foreach t in array array['materi','soal','modul','ppt','links'] loop
    begin
      execute format('alter publication supabase_realtime add table public.%I', t);
    exception when others then null;
    end;
  end loop;
end $$;

